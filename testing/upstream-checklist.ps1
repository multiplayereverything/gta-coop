# Builds coop-dev\UPSTREAM-SYNC-CHECKLIST.md: every item of the upstream CoopAndreas README TODO lists
# (https://github.com/Tornamic/CoopAndreas, our clone CoopAndreas\README.md), its upstream state, and what this
# fork did about it / where it is tracked (AGENTS.md "Sync backlog", MISSIONS.md). Re-run after rebasing on upstream.
#
#   powershell -ExecutionPolicy Bypass -File testing\upstream-checklist.ps1

$root = Split-Path -Parent $PSScriptRoot
$readme = Get-Content (Join-Path $root 'CoopAndreas\README.md')
$missions = Get-Content (Join-Path $root 'MISSIONS.md') -ErrorAction SilentlyContinue

# what this fork changed for specific upstream items (substring of the item -> note)
$ours = [ordered]@{
    'vote to skip'           = 'DONE here: verified 4/4 voting in ported + unported missions (lab, duo, sweep); unported missions sync cutscenes via fallback'
    'cutscenes'              = 'DONE here: cutscenes reach partners in unported missions too (fallback sync); other CJs hidden during cutscenes'
    'wanted level'           = 'PARTLY here: shared in unported missions (alter/clear_wanted_level replayed per player); free-roam wanted still per player'
    'sync money'             = 'PARTLY here: mission add_score shared in unported missions; free-roam money still per player'
    'Mission icons'          = 'verified: partner sees objective blips (duo lab objectiveBlips)'
    'gang groups sync'       = 'OPEN: tag gang-group in MISSIONS.md'
    'pickups'                = 'OPEN: tag pickups in MISSIONS.md'
    'fire sync'              = 'OPEN: tag fire in MISSIONS.md'
    'trailer sync'           = 'OPEN: tag trailers in MISSIONS.md'
    'force hydraulics sync'  = 'OPEN: Lowrider (High Stakes) closes the game when launched directly'
    'gang wars sync'         = 'OPEN: tag gang-wars in MISSIONS.md'
    'parachute jump sync'    = 'OPEN: tag parachute in MISSIONS.md'
    'stream in/out'          = 'OPEN'
}

function Note($item) {
    foreach ($k in $ours.Keys) { if ($item -like "*$k*") { return $ours[$k] } }
    return ''
}

$out = @('# Upstream CoopAndreas TODO vs this fork', '',
    'Generated by `testing/upstream-checklist.ps1` from the upstream README TODO lists',
    '(https://github.com/Tornamic/CoopAndreas). Every unchecked upstream item is also in AGENTS.md "Sync backlog".', '')

$section = ''
$rows = @()
foreach ($line in $readme) {
    if ($line -match '^## (TODO.*)$') { $section = $Matches[1]; continue }
    if (-not $section) { continue }
    if ($line -match '^(\s*)- \[([ xX])\] (.+)$') {
        $depth = [int]($Matches[1].Length / 2)
        $done = $Matches[2] -ne ' '
        $item = $Matches[3].Trim()
        $note = Note $item
        if ($section -like '*Missions*' -and $missions) {
            # names differ slightly between upstream and main.txt ("End Of The Line" vs "End Of The Line (1)")
            $lookup = if ($item -eq 'High Stakes, Low Rider') { 'Lowrider (High Stakes)' } else { $item }
            $norm = ($lookup.ToLower() -replace '[^a-z0-9]', '')
            $m = $missions | Where-Object { $_ -match '^\| \d+ ' } | Where-Object {
                $n = (($_ -split '\|')[3].ToLower() -replace '[^a-z0-9]', '')
                $n -eq $norm -or ($norm.Length -ge 6 -and ($n.StartsWith($norm) -or $n.Contains($norm)))
            } | Select-Object -First 1
            if ($m) { $c = $m -split '\|'; $note = "port: $($c[4].Trim()); 4-player sweep: $($c[5].Trim())" }
        }
        $rows += [pscustomobject]@{ Section = $section; Item = ('&nbsp;&nbsp;' * $depth) + $item; Upstream = $(if ($done) { 'done' } else { 'open' }); Here = $note }
    }
}
foreach ($s in $rows | Select-Object -ExpandProperty Section -Unique) {
    $out += "## $s", '', '| Item | Upstream | This fork / tracking |', '|---|---|---|'
    foreach ($r in $rows | Where-Object Section -eq $s) {
        $here = if ($r.Here) { $r.Here } elseif ($r.Upstream -eq 'open') { 'OPEN: in AGENTS.md Sync backlog' } else { '' }
        $out += "| $($r.Item) | $($r.Upstream) | $here |"
    }
    $out += ''
}
$open = @($rows | Where-Object { $_.Upstream -eq 'open' }).Count
$out += "Upstream items: $($rows.Count), open upstream: $open."
$out | Set-Content (Join-Path $root 'UPSTREAM-SYNC-CHECKLIST.md') -Encoding utf8
Write-Host "UPSTREAM-SYNC-CHECKLIST.md: $($rows.Count) items, $open open upstream"
